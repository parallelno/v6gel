"""Compile the exported knight's first frame into clipped 8080 drawing spans."""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'build/10_sprite_frame_onscr_ai'


def decode():
    data = (OUT / 'sprites/bin/KNIGHT.BIN').read_bytes()
    # The exporter stores alternating plane order, in screen-memory Y order.
    height, width = data[4:6]
    assert (height, width) == (15, 1)
    rows = []
    pos = 6
    for y in range(height):
        row = [None, None]
        for col in ([0, 1] if y % 2 == 0 else [1, 0]):
            mask, *planes = data[pos:pos + 4]
            pos += 4
            if col == 1:
                planes.reverse()
            row[col] = [mask, *planes]
        rows.append(row)
    return rows


def main():
    rows = decode()
    lines = ['; Generated by compile_sprite.py; do not edit.',
             '; Column-major spans: HL=destination, B=count; RET at clipped end.',
             'compiled_rows:']
    for y in range(15):
        lines.append('    .word ' + ', '.join(f'compiled_{col}_{y}' for col in range(6)))
    for column in range(6):
        for y, row in enumerate(rows):
            lines.append(f'compiled_{column}_{y}:')
            mask, *planes = row[column % 2]
            value = planes[column // 2]
            if mask == 0:
                lines.append(f'    mvi m, {value}')
            elif value == (mask ^ 255):
                lines += ['    mov a, m', f'    ori {value}', '    mov m, a']
            elif mask != 255 or value:
                lines += ['    mov a, m', f'    ani {mask}']
                if value:
                    lines.append(f'    ori {value}')
                lines.append('    mov m, a')
            lines += ['    dcr b', '    rz', '    inr l']
        lines.append('    ret')
    lines.append('compiled_full:')
    lines.append('    .word ' + ', '.join(f'full_{c}' for c in range(6)))
    for c in range(6):
        lines.append(f'full_{c}:')
        for y, row in enumerate(rows):
            mask, *planes = row[c % 2]
            value = planes[c // 2]
            if mask == 0:
                lines.append(f'    mvi m, {value}')
            elif value == (mask ^ 255):
                lines += ['    mov a, m', f'    ori {value}', '    mov m, a']
            else:
                lines += ['    mov a, m', f'    ani {mask}']
                if value:
                    lines.append(f'    ori {value}')
                lines.append('    mov m, a')
            if y != 14:
                lines.append('    inr l')
        lines.append('    ret')
    lines.append('draw_full_sprite:')
    current = 0
    for c in range(6):
        target = c % 2 + (c // 2) * 32
        if c:
            lines += ['    mov l, e', '    mov a, h', f'    adi {target-current}', '    mov h, a']
        current = target
        for y, row in enumerate(rows):
            mask, *planes = row[c % 2]
            value = planes[c // 2]
            if mask == 0:
                lines.append(f'    mvi m, {value}')
            elif value == (mask ^ 255):
                lines += ['    mov a, m', f'    ori {value}', '    mov m, a']
            else:
                lines += ['    mov a, m', f'    ani {mask}']
                if value:
                    lines.append(f'    ori {value}')
                lines.append('    mov m, a')
            if y != 14:
                lines.append('    inr l')
    lines.append('    ret')
    lines.append('restore_full_sprite:')
    for c in range(6):
        if c:
            lines += ['    mov l, e', '    mov a, h', f'    adi {1 if c % 2 else 31}', '    mov h, a']
        lines.append('    sphl')
        for _ in range(7):
            lines += ['    pop b', '    mov m, c', '    inr l', '    mov m, b', '    inr l']
        lines += ['    pop b', '    mov m, c']
    lines += ['    jmp restore_full_done']
    # Erase entry points for 1..32 rows. Banked stack reads don't map stores.
    lines += ['restore_lengths:', '    .word 0']
    lines += ['    .word ' + ', '.join(f'restore_{n}' for n in range(1, 33))]
    for n in range(1, 33):
        lines.append(f'restore_{n}:')
        for i in range(n // 2):
            lines += ['    pop b', '    mov m, c', '    inr l', '    mov m, b']
            if i * 2 + 2 < n:
                lines.append('    inr l')
        if n % 2:
            lines += ['    pop b', '    mov m, c']
        lines.append('    jmp restore_column_done')
    (OUT / 'compiled.asm').write_text('\n'.join(lines) + '\n')
    (OUT / 'sprite_reference.json').write_text(json.dumps(rows))


if __name__ == '__main__':
    main()